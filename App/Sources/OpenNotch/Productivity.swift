// MARK: - File shelf

struct ShelfItem: Identifiable, Codable, Equatable {
    var id = UUID()
    var path: String
    var added = Date()
}

/// Files parked in the notch. References only — the originals are never
/// copied or moved; dragging out hands the other app the original URL.
@MainActor
final class ShelfStore: ObservableObject {
    @Published private(set) var items: [ShelfItem] = []
    private let path = opennotchDir("") + "/shelf.json"

    init() {
        if let data = try? Data(contentsOf: URL(fileURLWithPath: path)),
           let saved = try? JSONDecoder().decode([ShelfItem].self, from: data) {
            items = saved
        }
    }

    func add(_ urls: [URL]) {
        for u in urls where !items.contains(where: { $0.path == u.path }) {
            items.insert(ShelfItem(path: u.path), at: 0)
        }
        save()
    }

    func remove(_ i: ShelfItem) { items.removeAll { $0.id == i.id }; save() }
    func clear() { items = []; save() }

    private func save() {
        if let data = try? JSONEncoder().encode(items) { try? data.write(to: URL(fileURLWithPath: path)) }
    }
}

struct ShelfView: View {
    @ObservedObject var store: ShelfStore
    @ObservedObject var backend: Backend
    @ObservedObject var hub: Hub
    @State private var targeted = false

    var body: some View {
        VStack(spacing: 0) {
            ModuleHeader(title: "Shelf", subtitle: "Drop files here, drag them out anywhere. Originals stay put.") {
                if !store.items.isEmpty {
                    Button("Clear") { store.clear() }.buttonStyle(.plain).font(.system(size: 11)).foregroundStyle(Theme.secondary)
                }
            }
            if store.items.isEmpty {
                EmptyHint(icon: "tray.and.arrow.down", text: "Drag files onto the notch and choose “Keep on Shelf”,\nor drop them right here.")
            } else {
                ScrollView {
                    LazyVGrid(columns: Array(repeating: GridItem(.flexible(), spacing: 10), count: 5), spacing: 12) {
                        ForEach(store.items) { item in tile(item) }
                    }
                    .padding(14)
                }
            }
        }
        .background(RoundedRectangle(cornerRadius: 14).fill(targeted ? Color.white.opacity(0.05) : .clear).padding(8))
        .onDrop(of: [.fileURL], isTargeted: $targeted) { providers in
            loadURLs(providers) { store.add($0) }
            return true
        }
    }

    private func tile(_ item: ShelfItem) -> some View {
        let exists = FileManager.default.fileExists(atPath: item.path)
        return VStack(spacing: 6) {
            appIcon(forPath: item.path, size: 44).resizable().frame(width: 44, height: 44)
            Text((item.path as NSString).lastPathComponent)
                .font(.system(size: 10.5)).lineLimit(2).multilineTextAlignment(.center)
                .foregroundStyle(exists ? .white.opacity(0.85) : .red.opacity(0.7))
        }
        .frame(maxWidth: .infinity)
        .padding(8)
        .background(RoundedRectangle(cornerRadius: 10).fill(.white.opacity(0.04)))
        .opacity(exists ? 1 : 0.5)
        .onDrag { NSItemProvider(contentsOf: URL(fileURLWithPath: item.path)) ?? NSItemProvider() }
        .onTapGesture(count: 2) { NSWorkspace.shared.open(URL(fileURLWithPath: item.path)) }
        .contextMenu {
            Button("Open") { NSWorkspace.shared.open(URL(fileURLWithPath: item.path)) }
            Button("Show in Finder") { NSWorkspace.shared.activateFileViewerSelecting([URL(fileURLWithPath: item.path)]) }
            Button("Ask Ledge about it") {
                backend.attach(Attachment(kind: .file, value: item.path))
                hub.module = .chat
            }
            Divider()
            Button("Remove from shelf") { store.remove(item) }
        }
        .help(item.path)
    }
}

// MARK: - Quick notes

/// A scratchpad that saves every edit (debounced) to ~/Library/Application Support/OpenNotch/notes.md.
@MainActor
final class NotesStore: ObservableObject {
    @Published var text: String = "" { didSet { scheduleSave() } }
    @Published private(set) var savedAt: Date?
    private let path = opennotchDir("") + "/notes.md"
    private var pending: DispatchWorkItem?

    init() {
        text = (try? String(contentsOfFile: path, encoding: .utf8)) ?? ""
    }

    /// Write now (on quit) — the debounced save might not have fired yet.
    func flush() {
        pending?.cancel()
        try? text.write(toFile: path, atomically: true, encoding: .utf8)
    }

    private func scheduleSave() {
        pending?.cancel()
        let snapshot = text
        let work = DispatchWorkItem { [weak self] in
            guard let self else { return }
            try? snapshot.write(toFile: self.path, atomically: true, encoding: .utf8)
            Task { @MainActor in self.savedAt = Date() }
        }
        pending = work
        DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + 0.4, execute: work)
    }
}

