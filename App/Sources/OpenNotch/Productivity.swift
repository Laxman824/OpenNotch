// MARK: - Clipboard history

struct Clip: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, link, image }
    var id = UUID()
    var kind: Kind
    var text: String?
    var imagePath: String?
    var date = Date()
    var app: String?
}

/// Local clipboard shelf: text, links and images, newest first. Polls the
/// pasteboard's change count (the only API macOS offers) and skips anything a
/// password manager marks concealed or transient — nspasteboard.org's
/// convention, honoured by 1Password, Bitwarden, KeePassXC and friends.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var clips: [Clip] = []
    private var lastChange = NSPasteboard.general.changeCount
    private var ignoreChange = -1
    private var suppressUntil = Date.distantPast
    private var timer: Timer?
    private let indexPath = opennotchDir("clips") + "/index.json"
    private let limit = 150

    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    func start() {
        if let data = try? Data(contentsOf: URL(fileURLWithPath: indexPath)),
           let saved = try? JSONDecoder().decode([Clip].self, from: data) {
            clips = saved
        }
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if pb.changeCount == ignoreChange || Date() < suppressUntil { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName

        // Skip enormous images (a 40-megapixel paste) rather than stall the main thread.
        let imageBytes = (pb.data(forType: .png) ?? pb.data(forType: .tiff))?.count ?? 0
        if imageBytes > 30_000_000 { return }
        if let img = NSImage(pasteboard: pb), types.contains(NSPasteboard.PasteboardType.png.rawValue)
            || types.contains(NSPasteboard.PasteboardType.tiff.rawValue),
           !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) {
            let clip = Clip(kind: .image, imagePath: nil, app: app)
            let path = opennotchDir("clips") + "/\(clip.id.uuidString).png"
            if let tiff = img.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff),
               let png = rep.representation(using: .png, properties: [:]) {
                try? png.write(to: URL(fileURLWithPath: path))
                var c = clip
                c.imagePath = path
                insert(c)
            }
            return
        }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let isLink = s.range(of: #"^\s*https?://\S+\s*$"#, options: .regularExpression) != nil
            insert(Clip(kind: isLink ? .link : .text, text: String(s.prefix(100_000)), app: app))
        }
    }

    /// Don't record clipboard changes for a moment — writing tools briefly use
    /// the clipboard to paste, and that isn't something you copied.
    func suppressNextChange(for seconds: TimeInterval = 1.5) {
        suppressUntil = Date().addingTimeInterval(seconds)
    }

    func addImage(path: String) {
        insert(Clip(kind: .image, imagePath: path, app: "OpenNotch"))
    }

    private func insert(_ c: Clip) {
        if c.kind != .image, let i = clips.firstIndex(where: { $0.text == c.text }) {
            clips.remove(at: i)                              // re-copied: move to top
        }
        clips.insert(c, at: 0)
        if clips.count > limit {
            for old in clips[limit...] { if let p = old.imagePath { try? FileManager.default.removeItem(atPath: p) } }
            clips = Array(clips.prefix(limit))
        }
        save()
    }

    func copy(_ c: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let p = c.imagePath, let img = NSImage(contentsOfFile: p) {
            pb.writeObjects([img])
        } else if let t = c.text {
            pb.setString(t, forType: .string)
        }
        ignoreChange = pb.changeCount                        // don't re-record our own copy
        if let i = clips.firstIndex(of: c) { clips.move(fromOffsets: IndexSet(integer: i), toOffset: 0); save() }
    }

    func delete(_ c: Clip) {
        if let p = c.imagePath { try? FileManager.default.removeItem(atPath: p) }
        clips.removeAll { $0.id == c.id }
        save()
    }

    func clear() {
        clips.forEach { if let p = $0.imagePath { try? FileManager.default.removeItem(atPath: p) } }
        clips = []
        save()
    }

    private func save() {
        if let data = try? JSONEncoder().encode(clips) { try? data.write(to: URL(fileURLWithPath: indexPath)) }
    }
}

struct ClipboardView: View {
    @ObservedObject var store: ClipboardStore
    @ObservedObject var backend: Backend
    @ObservedObject var hub: Hub
    @State private var filter = "All"
    @State private var query = ""
    @State private var copiedID: UUID?

    private var shown: [Clip] {
        store.clips.filter { c in
            switch filter {
            case "Text": return c.kind == .text
            case "Links": return c.kind == .link
            case "Images": return c.kind == .image
            default: return true
            }
        }.filter { c in query.isEmpty || (c.text ?? "").localizedCaseInsensitiveContains(query) }
    }

    var body: some View {
        VStack(spacing: 0) {
            ModuleHeader(title: "Clipboard", subtitle: "\(store.clips.count) items · stays on this Mac") {
                Button("Clear") { store.clear() }.buttonStyle(.plain).font(.system(size: 11)).foregroundStyle(Theme.secondary)
            }
            HStack(spacing: 6) {
                ForEach(["All", "Text", "Links", "Images"], id: \.self) { f in
                    Chip(label: f, selected: filter == f) { filter = f }
                }
                Spacer()
                SearchField(text: $query, placeholder: "Filter")
                    .frame(width: 150)
            }
            .padding(.horizontal, 18).padding(.bottom, 8)
            if shown.isEmpty {
                EmptyHint(icon: "doc.on.clipboard", text: "Copy anything — text, links, images, screenshots — and it lands here.")
            } else {
                ScrollView {
                    LazyVStack(spacing: 6) {
                        ForEach(shown) { c in row(c) }
                    }
                    .padding(.horizontal, 14).padding(.bottom, 14)
                }
            }
        }
    }

    @ViewBuilder
    private func row(_ c: Clip) -> some View {
        HStack(spacing: 10) {
            if c.kind == .image, let p = c.imagePath, let img = NSImage(contentsOfFile: p) {
                Image(nsImage: img).resizable().aspectRatio(contentMode: .fill)
                    .frame(width: 64, height: 44).clipShape(RoundedRectangle(cornerRadius: 6))
            } else {
                Image(systemName: c.kind == .link ? "link" : "text.alignleft")
                    .font(.system(size: 12)).foregroundStyle(Theme.secondary).frame(width: 22)
            }
            VStack(alignment: .leading, spacing: 3) {
                Text(c.kind == .image ? "Image" : (c.text ?? ""))
                    .font(.system(size: 12, design: c.kind == .link ? .monospaced : .default))
                    .lineLimit(2).foregroundStyle(.white.opacity(0.9))
                Text([c.app, relativeTime(c.date)].compactMap { $0 }.joined(separator: " · "))
                    .font(.system(size: 10)).foregroundStyle(Theme.tertiary)
            }
            Spacer(minLength: 0)
            if copiedID == c.id {
                Text("Copied").font(.system(size: 10, weight: .semibold)).foregroundStyle(.green)
            }
        }
        .padding(9)
        .background(RoundedRectangle(cornerRadius: 10).fill(.white.opacity(0.045)))
        .contentShape(RoundedRectangle(cornerRadius: 10))
        .onTapGesture {
            store.copy(c)
            copiedID = c.id
            DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { if copiedID == c.id { copiedID = nil } }
        }
        .onDrag {
            if let p = c.imagePath { return NSItemProvider(contentsOf: URL(fileURLWithPath: p)) ?? NSItemProvider() }
            return NSItemProvider(object: (c.text ?? "") as NSString)
        }
        .contextMenu {
            Button("Copy") { store.copy(c) }
            Button("Ask Ledge about this") {
                if let p = c.imagePath { backend.attach(Attachment(kind: .screenshot, value: p)) }
                else if let t = c.text { backend.attach(Attachment(kind: .clipboard, value: t)) }
                hub.module = .chat
            }
            Divider()
            Button("Delete") { store.delete(c) }
        }
    }
}

