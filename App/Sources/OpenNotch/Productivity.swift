// MARK: - File search (Spotlight)

struct FoundFile: Identifiable, Equatable {
    let id = UUID()
    let path: String
    let modified: Date?
}

/// Spotlight search by name *and* contents, the same index `mdfind` uses.
@MainActor
final class FileSearch: ObservableObject {
    @Published var query = ""
    @Published var contents = true
    @Published var scope = "Home"
    @Published private(set) var results: [FoundFile] = []
    @Published private(set) var searching = false
    /// Shown instead of results while waiting for / after refusing folder access.
    @Published private(set) var notice: String?
    /// Called before a folder access that may pop a macOS consent dialog
    /// (rule §5.3: the notch must get out of the dialog's way).
    var willPrompt: ((String) -> Void)?
    private var mdq: NSMetadataQuery?
    private var observer: NSObjectProtocol?
    private var readable: Set<String> = []   // folders already proven readable
    private var generation = 0

    func run() {
        mdq?.stop()
        if let observer { NotificationCenter.default.removeObserver(observer) }
        generation += 1
        let q = query.trimmingCharacters(in: .whitespaces)
        guard q.count >= 2 else { results = []; notice = nil; searching = false; return }
        let home = NSHomeDirectory()
        let dir = scope == "Home" ? home : "\(home)/\(scope)"
        if scope == "Home" || readable.contains(dir) {
            notice = nil
            start(q, dir)
            return
        }
        // Documents / Downloads / Desktop are TCC-protected. The first touch
        // (Spotlight resolves the scope with open()) blocks until the user
        // answers a consent dialog — on the main thread that froze the whole
        // notch (2026-09-30). Touch the folder on a background queue instead
        // and start the query only once access is known.
        let gen = generation, name = scope
        searching = true
        results = []
        notice = "Waiting for access to \(name) — answer the macOS dialog."
        // Already granted → the probe returns in milliseconds; only step the
        // notch aside if it's still waiting (i.e. a dialog is up).
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) {
            MainActor.assumeIsolated {
                if gen == self.generation, self.notice != nil, self.searching {
                    self.willPrompt?("OpenNotch to read your \(name) folder")
                }
            }
        }
        DispatchQueue.global(qos: .userInitiated).async { @Sendable in
            let ok = (try? FileManager.default.contentsOfDirectory(atPath: dir)) != nil
            DispatchQueue.main.async {
                MainActor.assumeIsolated {
                    guard gen == self.generation else { return }   // superseded
                    if ok {
                        self.readable.insert(dir)
                        self.notice = nil
                        self.start(q, dir)
                    } else {
                        self.searching = false
                        self.notice = "OpenNotch can't read \(name). Allow it in System Settings › Privacy & Security › Files and Folders, or search Home."
                    }
                }
            }
        }
    }

    private func start(_ q: String, _ dir: String) {
        let m = NSMetadataQuery()
        let escaped = q.replacingOccurrences(of: "\"", with: "")
        let name = NSPredicate(format: "%K CONTAINS[cd] %@", NSMetadataItemFSNameKey, escaped)
        m.predicate = contents
            ? NSCompoundPredicate(orPredicateWithSubpredicates: [
                name, NSPredicate(format: "kMDItemTextContent CONTAINS[cd] %@", escaped)])
            : name
        m.searchScopes = [dir]
        m.sortDescriptors = [NSSortDescriptor(key: NSMetadataItemFSContentChangeDateKey, ascending: false)]
        searching = true
        observer = NotificationCenter.default.addObserver(forName: .NSMetadataQueryDidFinishGathering,
                                                          object: m, queue: .main) { [weak self] _ in
            Task { @MainActor in
                guard let self else { return }
                m.disableUpdates()
                var out: [FoundFile] = []
                for i in 0..<min(m.resultCount, 80) {
                    guard let item = m.result(at: i) as? NSMetadataItem,
                          let p = item.value(forAttribute: NSMetadataItemPathKey) as? String,
                          !p.contains("/Library/"), !p.contains("/."), !p.contains("/node_modules/") else { continue }
                    out.append(FoundFile(path: p, modified: item.value(forAttribute: NSMetadataItemFSContentChangeDateKey) as? Date))
                }
                self.results = out
                self.searching = false
                m.stop()
            }
        }
        mdq = m
        m.start()
    }
}

struct FilesView: View {
    @ObservedObject var store: FileSearch
    @ObservedObject var backend: Backend
    @ObservedObject var hub: Hub

    var body: some View {
        VStack(spacing: 0) {
            ModuleHeader(title: "Find files", subtitle: "Spotlight — names\(store.contents ? " and contents" : "")") {
                if store.searching { ProgressView().controlSize(.small) }
            }
            HStack(spacing: 6) {
                SearchField(text: $store.query, placeholder: "Search your Mac…", onSubmit: store.run)
                Chip(label: "Contents", icon: "text.magnifyingglass", selected: store.contents) {
                    store.contents.toggle(); store.run()
                }
                Menu(store.scope) {
                    ForEach(["Home", "Documents", "Downloads", "Desktop"], id: \.self) { s in
                        Button(s) { store.scope = s; store.run() }
                    }
                }
                .menuStyle(.button).buttonStyle(.plain).fixedSize()
                .font(.system(size: 11)).foregroundStyle(Theme.secondary)
            }
            .padding(.horizontal, 18).padding(.bottom, 8)
            .onChange(of: store.query) { _ in
                NSObject.cancelPreviousPerformRequests(withTarget: store)
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.35) { store.run() }
            }
            if store.results.isEmpty {
                EmptyHint(icon: store.notice == nil ? "doc.text.magnifyingglass" : "lock.shield",
                          text: store.notice ?? (store.query.count < 2 ? "Type to search file names and what's inside them.\nOr just ask Ledge: “find my offer letter PDF”."
                                                      : (store.searching ? "Searching…" : "Nothing found.")))
            } else {
                ScrollView {
                    LazyVStack(spacing: 4) {
                        ForEach(store.results) { f in fileRow(f) }
                    }
                    .padding(.horizontal, 14).padding(.bottom, 12)
                }
            }
        }
    }

    private func fileRow(_ f: FoundFile) -> some View {
        HStack(spacing: 10) {
            appIcon(forPath: f.path, size: 26).resizable().frame(width: 26, height: 26)
            VStack(alignment: .leading, spacing: 2) {
                Text((f.path as NSString).lastPathComponent).font(.system(size: 12, weight: .medium)).lineLimit(1)
                Text(f.path.replacingOccurrences(of: NSHomeDirectory(), with: "~"))
                    .font(.system(size: 10, design: .monospaced)).foregroundStyle(Theme.tertiary)
                    .lineLimit(1).truncationMode(.middle)
            }
            Spacer(minLength: 0)
            if let m = f.modified {
                Text(relativeTime(m)).font(.system(size: 10)).foregroundStyle(Theme.tertiary)
            }
        }
        .padding(7)
        .background(RoundedRectangle(cornerRadius: 9).fill(.white.opacity(0.035)))
        .contentShape(Rectangle())
        .onTapGesture(count: 2) { NSWorkspace.shared.open(URL(fileURLWithPath: f.path)) }
        .onDrag { NSItemProvider(contentsOf: URL(fileURLWithPath: f.path)) ?? NSItemProvider() }
        .contextMenu {
            Button("Open") { NSWorkspace.shared.open(URL(fileURLWithPath: f.path)) }
            Button("Show in Finder") { NSWorkspace.shared.activateFileViewerSelecting([URL(fileURLWithPath: f.path)]) }
            Button("Ask Ledge about it") {
                backend.attach(Attachment(kind: .file, value: f.path)); hub.module = .chat
            }
            Button("Keep on Shelf") { hub.shelf.add([URL(fileURLWithPath: f.path)]) }
            Button("Copy path") { copyToClipboard(f.path) }
        }
    }
}
